"""Loads the seed dataset and generates the transmission corridor topology.

Provenance, stated plainly because it matters for how much the results mean:
  - Substations, generating stations and load centres are REAL entities. Names,
    fuel types and installed capacities come from public CEA / Grid-India
    material and are rounded. Coordinates are approximate -- they point at the
    named town, not the surveyed switchyard.
  - The seven HVDC bipoles in ``fixed_lines`` are real corridors.
  - The AC corridor topology is SYNTHETIC, generated by ``generate_lines()``.

Generation is deterministic -- no randomness anywhere -- so re-seeding
reproduces exactly the same network.
"""
from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from math import asin, cos, radians, sin, sqrt
from pathlib import Path
from typing import Any

DATA_FILE = Path(__file__).resolve().parent.parent / "data" / "grid.json"

K_NEAREST = 3
MAX_SPAN_KM = 450


@lru_cache(maxsize=1)
def load_dataset() -> dict[str, Any]:
    with DATA_FILE.open() as fh:
        return json.load(fh)


def haversine_km(a: dict, b: dict) -> int:
    """Great-circle distance in km. Good enough for line lengths at this scale."""
    radius = 6371
    d_lat = radians(b["lat"] - a["lat"])
    d_lon = radians(b["lon"] - a["lon"])
    h = (
        sin(d_lat / 2) ** 2
        + cos(radians(a["lat"])) * cos(radians(b["lat"])) * sin(d_lon / 2) ** 2
    )
    return round(2 * radius * asin(sqrt(h)))


def _rating_for(kv: int) -> int:
    """Thermal rating implied by the lower of the two terminal voltages."""
    if kv >= 765:
        return 2400
    if kv >= 400:
        return 1200
    if kv >= 220:
        return 400
    return 200


class _UnionFind:
    def __init__(self) -> None:
        self._parent: dict[str, str] = {}

    def find(self, x: str) -> str:
        parent = self._parent.setdefault(x, x)
        if parent != x:
            parent = self.find(parent)
            self._parent[x] = parent
        return parent

    def union(self, a: str, b: str) -> bool:
        ra, rb = self.find(a), self.find(b)
        if ra == rb:
            return False
        self._parent[ra] = rb
        return True


@dataclass
class Line:
    line_id: str
    name: str
    from_id: str
    to_id: str
    capacity_mw: int
    voltage_kv: int
    length_km: int
    status: str
    hvdc: bool

    def as_row(self) -> dict[str, Any]:
        return {
            "line_id": self.line_id,
            "name": self.name,
            "from": self.from_id,
            "to": self.to_id,
            "capacity_mw": self.capacity_mw,
            "voltage_kv": self.voltage_kv,
            "length_km": self.length_km,
            "status": self.status,
            "hvdc": self.hvdc,
        }


def generate_lines() -> list[Line]:
    """Build the AC corridor set in three passes.

    1. Hardcoded real corridors (HVDC bipoles, long inter-regional 765 kV ties).
       These are exactly what a nearest-neighbour heuristic would never produce,
       and they are what makes the graph interesting: one bipole can carry the
       entire supply of a distant region.
    2. k-nearest-neighbour meshing within MAX_SPAN_KM, which yields the ~4.1
       average degree that makes the graph behave like a real transmission
       network rather than a tree.
    3. Connectivity repair: while more than one component exists, join the two
       closest substations in different components. Guarantees a single connected
       grid, which the contingency query depends on being meaningful.
    """
    data = load_dataset()
    substations: list[dict] = data["substations"]
    by_id = {s["id"]: s for s in substations}

    lines: list[Line] = []
    seen: set[tuple[str, str]] = set()
    uf = _UnionFind()
    for s in substations:
        uf.find(s["id"])

    def key(a: str, b: str) -> tuple[str, str]:
        return (a, b) if a < b else (b, a)

    def push(
        a: str, b: str, name: str, capacity_mw: int, voltage_kv: int, hvdc: bool
    ) -> None:
        if a == b or key(a, b) in seen:
            return
        if a not in by_id or b not in by_id:
            raise ValueError(f"Line references unknown substation: {a} -> {b}")
        seen.add(key(a, b))
        uf.union(a, b)
        lines.append(
            Line(
                line_id=f"L-{len(lines) + 1:04d}",
                name=name,
                from_id=a,
                to_id=b,
                capacity_mw=capacity_mw,
                voltage_kv=voltage_kv,
                length_km=haversine_km(by_id[a], by_id[b]),
                status="IN_SERVICE",
                hvdc=hvdc,
            )
        )

    # 1. Real corridors first, so they keep the low, memorable line ids.
    for fixed in data["fixed_lines"]:
        push(
            fixed["from"], fixed["to"], fixed["name"],
            fixed["capacity_mw"], fixed["voltage_kv"], fixed["hvdc"],
        )

    # 2. k-NN mesh.
    for a in substations:
        neighbours = sorted(
            (
                (haversine_km(a, b), b)
                for b in substations
                if b["id"] != a["id"] and haversine_km(a, b) <= MAX_SPAN_KM
            ),
            key=lambda pair: (pair[0], pair[1]["id"]),
        )[:K_NEAREST]
        for _, b in neighbours:
            kv = min(a["voltage_kv"], b["voltage_kv"])
            push(a["id"], b["id"], f"{a['name']}–{b['name']} {kv}kV",
                 _rating_for(kv), kv, False)

    # 3. Connectivity repair.
    while len({uf.find(s["id"]) for s in substations}) > 1:
        best = None
        for a in substations:
            for b in substations:
                if uf.find(a["id"]) == uf.find(b["id"]):
                    continue
                d = haversine_km(a, b)
                if best is None or d < best[0]:
                    best = (d, a, b)
        if best is None:
            break
        _, a, b = best
        kv = min(a["voltage_kv"], b["voltage_kv"])
        push(a["id"], b["id"], f"{a['name']}–{b['name']} {kv}kV",
             _rating_for(kv), kv, False)

    return lines


def compute_corridor_load(lines: list[Line]) -> dict[str, dict[str, float]]:
    """Precompute the Q4 corridor ranking: generation routed through each line.

    Why this is not a live query. The equivalent Cypher (kept in
    ``app.queries.CRITICAL_LINES_LIVE``) runs ``shortestPath`` across every
    plant/city pair -- 44 source substations by 60 cities, ~2,600 path searches.
    Neo4j answers it in ~190 ms; the CognoDB free tier (0.5 vCPU burstable) took
    19 s and then began timing out. The metric is a pure function of the topology
    and does not depend on the outage set, so it is computed once at seed time
    and stored on the relationship. The API then reads a property and sorts.

    Deterministic: BFS explores neighbours in line-id order, so ties break the
    same way on every run and re-seeding reproduces identical numbers.
    """
    from collections import deque

    data = load_dataset()
    adj: dict[str, list[tuple[str, str]]] = {}
    for line in lines:
        adj.setdefault(line.from_id, []).append((line.to_id, line.line_id))
        adj.setdefault(line.to_id, []).append((line.from_id, line.line_id))
    for neighbours in adj.values():
        neighbours.sort(key=lambda pair: pair[1])

    plants_at: dict[str, list[dict]] = {}
    for plant in data["plants"]:
        plants_at.setdefault(plant["substation"], []).append(plant)
    sinks = {city["substation"] for city in data["load_centres"]}

    load: dict[str, dict[str, float]] = {
        line.line_id: {"mw_carried": 0.0, "paths_carried": 0} for line in lines
    }

    for src, plants in plants_at.items():
        # One BFS per source substation yields the shortest path to every sink.
        prev: dict[str, tuple[str, str]] = {}
        seen = {src}
        queue = deque([src])
        while queue:
            node = queue.popleft()
            for neighbour, line_id in adj.get(node, []):
                if neighbour not in seen:
                    seen.add(neighbour)
                    prev[neighbour] = (node, line_id)
                    queue.append(neighbour)

        src_mw = sum(p["capacity_mw"] for p in plants)
        for sink in sinks:
            if sink == src or sink not in prev:
                continue
            node = sink
            while node != src:
                parent, line_id = prev[node]
                load[line_id]["mw_carried"] += src_mw
                load[line_id]["paths_carried"] += len(plants)
                node = parent

    return load
